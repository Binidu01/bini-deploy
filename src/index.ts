function toWorkerName(name: string): string {
  const cleaned = name
    .toLowerCase()
    .replace(/[^a-z0-9-]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 63)
    .replace(/-+$/g, '');
  return cleaned || 'my-app';
}

function isTypeScriptProject(): boolean {
  const cwd = process.cwd();

  const mainEntries = ['src/main.tsx', 'src/main.ts', 'src/main.jsx', 'src/main.js'];
  for (const entry of mainEntries) {
    if (existsSync(path.join(cwd, entry))) {
      return entry.includes('.ts');
    }
  }

  if (existsSync(path.join(cwd, 'tsconfig.json'))) return true;

  const appDir = path.join(cwd, 'src/app');
  if (existsSync(appDir)) {
    const hasTsFile = (dir: string, depth = 0): boolean => {
      if (depth > 5) return false;
      try {
        const entries = readdirSync(dir, { withFileTypes: true });
        for (const entry of entries) {
          if (entry.isDirectory()) {
            if (hasTsFile(path.join(dir, entry.name), depth + 1)) return true;
          } else {
            const ext = path.extname(entry.name);
            if (ext === '.tsx' || ext === '.ts') return true;
          }
        }
      } catch {
        return false;
      }
      return false;
    };
    if (hasTsFile(appDir)) return true;
  }

  return false;
}

/** True when the API directory contains at least one route file. */
function hasApiRoutes(dir: string, depth = 0): boolean {
  if (depth > MAX_API_SCAN_DEPTH || !existsSync(dir)) return false;
  try {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (entry.name.startsWith('_') || entry.name.startsWith('.')) continue;
      if (entry.isDirectory()) {
        if (hasApiRoutes(path.join(dir, entry.name), depth + 1)) return true;
      } else if ((API_EXTS as readonly string[]).includes(path.extname(entry.name))) {
        return true;
      }
    }
  } catch {
    return false;
  }
  return false;
}

function relativeApiImport(outFile: string): string {
  const target = path.join(process.cwd(), COMPILED_API_FILE);
  const rel = toPosixPath(path.relative(path.dirname(outFile), target));
  return rel.startsWith('.') ? rel : `./${rel}`;
}

