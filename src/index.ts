const fromRoot = (cwd: string, rel: string): string => path.join(cwd, ...rel.split('/'));

function readTextSafe(file: string): string | null {
  try {
    return readFileSync(file, 'utf8');
  } catch {
    return null;
  }
}

function isGeneratedFile(file: string): boolean {
  return readTextSafe(file)?.includes(GENERATED_MARKER) ?? false;
}

function parseJsonObject(file: string): JsonObject | null {
  const text = readTextSafe(file);
  if (text === null) return null;
  try {
    const value: unknown = JSON.parse(text);
    return value && typeof value === 'object' && !Array.isArray(value) ? (value as JsonObject) : null;
  } catch {
    return null;
  }
}

// vercel.json cannot hold a marker comment, so a file counts as ours when it
// has only the keys bini-deploy writes.
function isGeneratedVercelConfig(file: string): boolean {
  const json = parseJsonObject(file);
  return (
    json !== null &&
    Object.keys(json).every((k) => k === 'buildCommand' || k === 'rewrites' || k === 'base')
  );
}

function isGeneratedApiTsconfig(file: string): boolean {
  const json = parseJsonObject(file);
  if (!json) return false;
  const compilerOptions = json.compilerOptions as { types?: unknown } | null | undefined;
  const types = compilerOptions?.types;
  return (
    json.extends === '../tsconfig.json' &&
    Object.keys(json).every((k) => k === 'extends' || k === 'compilerOptions') &&
    Array.isArray(types) &&
    types.length === 0
  );
}

function isGeneratedConfig(platform: NonNodePlatform, file: string): boolean {
  return platform === 'vercel' ? isGeneratedVercelConfig(file) : isGeneratedFile(file);
}

function removeGenerated(file: string, isGenerated: (f: string) => boolean, dryRun: boolean): void {
  if (!existsSync(file) || !isGenerated(file)) return;
  const rel = toPosixPath(path.relative(process.cwd(), file));
  if (dryRun) {
    log.info(`Would remove: ${rel}`);
    return;
  }
  try {
    unlinkSync(file);
    log.info(`Removed old file: ${rel}`);
  } catch {
    // ignore
  }
}

function pruneEmptyDir(dir: string): void {
  try {
    if (existsSync(dir) && readdirSync(dir).length === 0) rmdirSync(dir);
  } catch {
    // ignore
  }
}

/**
 * Removes what bini-deploy generated for the platforms that are NOT selected.
 * Only files carrying the generated marker (or, for vercel.json and
 * api/tsconfig.json, exactly the content we write) are deleted, and folders
 * only when they end up empty, so your own files are never touched.
 */
function cleanupPlatformArtifacts(hosting: Platform, ts: boolean, dryRun = false): void {
  const cwd = process.cwd();
  const allPlatforms: NonNodePlatform[] = ['netlify', 'vercel', 'cloudflare', 'deno'];

  for (const platform of allPlatforms) {
    if (platform === hosting) {
      // Same platform: only drop the entry generated for the other language (.ts <-> .js).
      const adapter = ADAPTERS[platform];
      const current = adapter.outFile(cwd, ts);
      const other = adapter.outFile(cwd, !ts);
      if (other !== current) removeGenerated(other, isGeneratedFile, dryRun);
      continue;
    }

    for (const rel of GENERATED_ENTRY_FILES[platform]) {
      removeGenerated(fromRoot(cwd, rel), isGeneratedFile, dryRun);
    }
    if (platform === 'vercel') {
      removeGenerated(path.join(cwd, 'api', 'tsconfig.json'), isGeneratedApiTsconfig, dryRun);
    }

    const configFile = HOSTING_CONFIGS[platform].configFile;
    if (configFile) {
      removeGenerated(path.join(cwd, configFile), (f) => isGeneratedConfig(platform, f), dryRun);
    }

    if (!dryRun) {
      for (const rel of GENERATED_DIRS[platform]) pruneEmptyDir(fromRoot(cwd, rel));
    }
  }
}

export async function generateProductionEntry(platform: NonNodePlatform, apiDir?: string): Promise<void> {
  const cwd = process.cwd();
  const srcApiDir = apiDir || path.join(cwd, 'src/app/api');

  // SSG + outdated router would produce silently broken dynamic shells on every host.
  assertShellApiWhenSsg(cwd);

  const ts = isTypeScriptProject();
  const hasApi = hasApiRoutes(srcApiDir);
  const base = detectRouterBase(cwd);

  cleanupPlatformArtifacts(platform, ts);

  const adapter = ADAPTERS[platform];
  const outFile = adapter.outFile(cwd, ts);

  // Deno's entry is also its static file server, so it is always generated.
  if (!hasApi && platform !== 'deno') {
    log.info('No API routes found, so no API entry is needed for this host.');
    // Drop an entry left over from an earlier run that did have routes.
    for (const file of new Set([adapter.outFile(cwd, true), adapter.outFile(cwd, false)])) {
      removeGenerated(file, isGeneratedFile, false);
    }
    return;
  }

  if (hasApi) {
    log.info(`API routes found. The entry will serve ${toPosixPath(COMPILED_API_FILE)}`);
  } else {
    log.info('No API routes found. Generating a static-only Deno server.');
  }
  if (base) log.info(`Using router base: ${base}`);

  const dir = path.dirname(outFile);
  if (!existsSync(dir)) {
    mkdirSync(dir, { recursive: true });
  }

  const content = buildEntryContent(platform, outFile, hasApi, base);

  try {
    writeFileSync(outFile, content, 'utf8');
    log.success(`Generated: ${toPosixPath(path.relative(cwd, outFile))}`);
  } catch (error) {
    log.error(`Failed to write production entry file: ${error instanceof Error ? error.message : String(error)}`);
    throw error;
  }
}

// Never overwrite a config the user wrote themselves.
function canWriteConfig(platform: NonNodePlatform, file: string): boolean {
  if (!existsSync(file) || isGeneratedConfig(platform, file)) return true;
  log.warn(
    `${path.basename(file)} already exists and was not generated by bini-deploy, so it was left untouched. ` +
      'Merge the settings by hand if needed.',
  );
  return false;
}

async function generateHostingConfig(
  hosting: NonNodePlatform,
  projectName: string,
  hasApi: boolean,
): Promise<string | null> {
  const cwd = process.cwd();
  const pm = detectPackageManager();
  const base = detectRouterBase(cwd);
  const ssg = usesSsg(cwd);

  cleanupPlatformArtifacts(hosting, isTypeScriptProject());

  const configFile = HOSTING_CONFIGS[hosting].configFile;
  if (!configFile) return null;

  const outFile = path.join(cwd, configFile);
  const buildCommand = scriptCommand(pm, 'build');
  const writeConfig = canWriteConfig(hosting, outFile);

  const apiSource = withBase(base, '/api');
  const apiSourceSplat = withBase(base, '/api/(.*)');
  const pageSource = withBase(base, '/((?!.*\\.[a-zA-Z0-9]+$).*)');

  switch (hosting) {
    case 'netlify': {
      // The API runs as a Netlify Function (netlify/functions/api.mjs) that
      // declares its own path, so no [[edge_functions]] entry is needed.
      // For SSG builds, prefer 404.html over SPA home-page fallback.
      const config =
        `# ${GENERATED_MARKER} - do not edit.\n` +
        `[build]\n  command = "${buildCommand}"\n  publish = "dist"\n` +
        (hasApi ? `\n[functions]\n  included_files = ["dist/api/**"]\n` : '') +
        (ssg
          ? `\n# SSG: serve the real 404 page instead of rewriting every miss to the home page.\n[[redirects]]\n  from = "/*"\n  to = "/404.html"\n  status = 404\n`
          : '');
      if (writeConfig) await writeFile(outFile, config);

      const ts = isTypeScriptProject();
      const edgeDir = path.join(cwd, 'netlify', 'edge-functions');
      mkdirSync(edgeDir, { recursive: true });

      // Remove the old Edge Function API entry and the other-language SPA fallback
      // (only files we generated).
      for (const stale of ['api.ts', 'api.js', ts ? 'spa-fallback.js' : 'spa-fallback.ts']) {
        removeGenerated(path.join(edgeDir, stale), isGeneratedFile, false);
      }

      // With SSG, Netlify static hosting + 404.html is enough; the edge SPA
      // fallback would send unknown routes to the home page. Only emit it for
      // pure SPA (no bini-ssg).
      if (!ssg) {
        const excludedApi = withBase(base, '/api/*');
        const fallbackBody = ts
          ? `// ${GENERATED_MARKER} - do not edit.
import type { Context } from 'https://edge.netlify.com';

export default async (request: Request, context: Context) => {
  const response = await context.next();
  const { pathname } = new URL(request.url);
  const isPage =
    (request.method === 'GET' || request.method === 'HEAD') &&
    !/\\.[a-zA-Z0-9]+$/.test(pathname);
  if (response.status === 404 && isPage) {
    return context.rewrite(${JSON.stringify(withBase(base, '/index.html'))});
  }
  return response;
};

export const config = { path: '/*', excludedPath: [${JSON.stringify(excludedApi)}] };
`
          : `// ${GENERATED_MARKER} - do not edit.
export default async (request, context) => {
  const response = await context.next();
  const { pathname } = new URL(request.url);
  const isPage =
    (request.method === 'GET' || request.method === 'HEAD') &&
    !/\\.[a-zA-Z0-9]+$/.test(pathname);
  if (response.status === 404 && isPage) {
    return context.rewrite(${JSON.stringify(withBase(base, '/index.html'))});
  }
  return response;
};

export const config = { path: '/*', excludedPath: [${JSON.stringify(excludedApi)}] };
`;
        await writeFile(path.join(edgeDir, ts ? 'spa-fallback.ts' : 'spa-fallback.js'), fallbackBody);
      } else {
        // Drop a leftover SPA fallback from a previous non-SSG deploy.
        for (const stale of ['spa-fallback.ts', 'spa-fallback.js']) {
          removeGenerated(path.join(edgeDir, stale), isGeneratedFile, false);
        }
      }
      return writeConfig ? outFile : null;
    }

    case 'vercel': {
      // API rewrite is always needed when routes exist.
      // For SSG: do NOT blanket-rewrite pages to /index.html (that is the home
      // page). Unknown paths should hit 404.html / filesystem shells.
      // For SPA (no ssg): keep the classic client-router fallback.
      const rewrites: Array<{ source: string; destination: string }> = [
        ...(hasApi
          ? [{ source: apiSourceSplat, destination: withBase(base, '/api/index') }]
          : []),
      ];
      if (!ssg) {
        rewrites.push({
          source: pageSource,
          destination: withBase(base, '/index.html'),
        });
      }
      if (writeConfig) {
        await writeFile(
          outFile,
          JSON.stringify(
            {
              buildCommand,
              ...(base ? { base } : {}),
              rewrites,
            },
            null,
            2,
          ),
        );
      }

      if (hasApi && isTypeScriptProject()) {
        const apiDir = path.join(cwd, 'api');
        const tsconfigFile = path.join(apiDir, 'tsconfig.json');
        if (!existsSync(tsconfigFile) || isGeneratedApiTsconfig(tsconfigFile)) {
          mkdirSync(apiDir, { recursive: true });
          await writeFile(
            tsconfigFile,
            JSON.stringify(
              {
                extends: '../tsconfig.json',
                compilerOptions: { types: [], skipLibCheck: true },
              },
              null,
              2,
            ) + '\n',
          );
        }
      }

      return writeConfig ? outFile : null;
    }

    case 'cloudflare': {
      const ts = isTypeScriptProject();
      const workerName = toWorkerName(projectName);
      const workerFirst = withBase(base, '/api/*');

      // Without API routes there is no Worker: assets only.
      const lines = [`# ${GENERATED_MARKER} - do not edit.`, `name = "${workerName}"`];
      if (hasApi) lines.push(`main = "${ts ? 'worker.ts' : 'worker.js'}"`);
      lines.push(`compatibility_date = "2025-04-09"`);
      if (hasApi) lines.push(`compatibility_flags = ["nodejs_compat"]`);
      // Tell `wrangler deploy` not to treat this file as the source of truth for
      // plain-text variables, so dashboard variables survive redeploys. Secrets
      // are unaffected either way.
      lines.push(`keep_vars = true`);
      lines.push('', '[assets]', 'directory = "./dist"');
      if (hasApi) lines.push('binding = "ASSETS"');
      // Prefer the real 404.html from SSG over a soft SPA miss.
      lines.push('not_found_handling = "404-page"');
      if (hasApi) lines.push(`run_worker_first = ["${workerFirst}"]`);
      if (writeConfig) await writeFile(outFile, lines.join('\n') + '\n');

      // Vite copies public/ into dist/, so this keeps the compiled API bundle
      // and build internals from being uploaded as static assets. Existing
      // lines in the file are kept.
      const publicDir = path.join(cwd, 'public');
      mkdirSync(publicDir, { recursive: true });
      const ignoreFile = path.join(publicDir, '.assetsignore');
      const existing = (readTextSafe(ignoreFile) ?? '').split(/\r?\n/).filter(Boolean);
      for (const entry of ['/api/', '/.bini/']) {
        if (!existing.includes(entry)) existing.push(entry);
      }
      await writeFile(ignoreFile, existing.join('\n') + '\n');

      return writeConfig ? outFile : null;
    }

    default:
      return null;
  }
}

