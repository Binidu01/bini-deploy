/**
 * Vite `base` as a path prefix without trailing slash ('' for root).
 * Reads BINI_BASE / VITE_BASE / BASE env first, then falls back to scanning
 * vite.config.* for `base: '...'`.
 */
function detectRouterBase(cwd = process.cwd()): string {
  for (const key of ['BINI_BASE', 'VITE_BASE', 'BASE']) {
    const raw = process.env[key]?.trim();
    if (raw === undefined) continue;
    if (!raw || raw === '/' || raw === '.' || raw === './') return '';
    return '/' + raw.replace(/^\/+|\/+$/g, '');
  }
  for (const name of ['vite.config.ts', 'vite.config.js', 'vite.config.mts', 'vite.config.mjs']) {
    const file = path.join(cwd, name);
    if (!existsSync(file)) continue;
    try {
      const text = readFileSync(file, 'utf8');
      const m = /\bbase\s*:\s*['"]([^'"]+)['"]/.exec(text);
      if (m) {
        const raw = m[1].trim();
        if (!raw || raw === '/' || raw === '.' || raw === './') return '';
        return '/' + raw.replace(/^\/+|\/+$/g, '');
      }
    } catch {
      /* ignore */
    }
  }
  return '';
}

/** True when the project depends on bini-ssg (static prerender + shells). */
function usesSsg(cwd = process.cwd()): boolean {
  try {
    const pkg = JSON.parse(readFileSync(path.join(cwd, 'package.json'), 'utf8')) as PackageJson;
    const deps = { ...pkg.dependencies, ...pkg.devDependencies };
    return Boolean(deps['bini-ssg']);
  } catch {
    return false;
  }
}

/**
 * When SSG is in use, require a bini-router that exports getShellRoutes.
 * A missing API would produce silently broken /blog/42 rewrites on every host.
 */
function assertShellApiWhenSsg(cwd = process.cwd()): void {
  if (!usesSsg(cwd)) return;
  try {
    // Resolve the project's own bini-router (works with file: / workspace links).
    const routerPkg = path.join(cwd, 'node_modules', 'bini-router');
    const entryCandidates = [
      path.join(routerPkg, 'dist', 'index.js'),
      path.join(routerPkg, 'dist', 'index.mjs'),
      path.join(routerPkg, 'index.js'),
    ];
    let src: string | null = null;
    for (const c of entryCandidates) {
      if (existsSync(c)) {
        src = readFileSync(c, 'utf8');
        break;
      }
    }
    // Also check the package exports / types for the symbol name.
    const typesFile = path.join(routerPkg, 'dist', 'index.d.ts');
    const types = existsSync(typesFile) ? readFileSync(typesFile, 'utf8') : '';
    const hasApi =
      (src && /\bgetShellRoutes\b/.test(src)) ||
      (types && /\bgetShellRoutes\b/.test(types));
    if (!hasApi) {
      throw new Error(
        'bini-ssg is installed but bini-router is too old (missing getShellRoutes).\n' +
          '  Upgrade bini-router to a version that exports getShellRoutes / clientOnly,\n' +
          '  then re-run bini-deploy. Without it, dynamic shells like /blog/42 will 404.',
      );
    }
  } catch (err) {
    if (err instanceof Error && err.message.includes('getShellRoutes')) throw err;
    // If bini-router is not resolvable yet, warn rather than hard-fail (fresh clone).
    log.warn(
      'Could not verify bini-router getShellRoutes. Ensure bini-router is installed and up to date when using bini-ssg.',
    );
  }
}

/** Prefix a path with the router base ('' when root). */
function withBase(base: string, p: string): string {
  if (!base) return p;
  if (p === '/') return base || '/';
  return base + (p.startsWith('/') ? p : '/' + p);
}

